import assert from "node:assert/strict";
import { toDate, parseAmount, appAmount, last4, accountSlug, guessKind, cleanMerchant } from "./tiller-lib.mjs";

assert.equal(toDate("2/4/2026"), "2026-02-04");
assert.equal(toDate("2026-02-04"), "2026-02-04");
assert.equal(toDate("garbage"), null);
assert.equal(parseAmount("-$12.34"), -12.34);
assert.equal(parseAmount("($12.34)"), -12.34);
assert.equal(parseAmount("$1,234.50"), 1234.5);
assert.equal(parseAmount("12.34-"), -12.34);
assert.equal(parseAmount(""), null);
assert.equal(parseAmount("n/a"), null);
assert.equal(appAmount(-242.88), 242.88);
assert.equal(appAmount(15), -15);
assert.equal(appAmount(0), 0);
assert.equal(last4("xxxx0848", ""), "0848");
assert.equal(last4("", "Blue Cash Everyday (-1008)"), "1008");
assert.equal(last4("", "EVERYDAY CHECKING ...0848"), "0848");
assert.equal(last4("", "Cash Management (Individual)"), "");
assert.equal(accountSlug("EVERYDAY CHECKING ...0848", "0848"), "everyday-checking-0848");
assert.equal(accountSlug("Blue Cash Everyday (-1008)", "1008"), "blue-cash-everyday-1008");
assert.equal(accountSlug("Cash Management (Individual)", ""), "cash-management-individual");
assert.equal(guessKind({ name: "EVERYDAY CHECKING ...0848" }), "checking");
assert.equal(guessKind({ name: "Blue Cash Everyday (-1008)" }), "credit");
assert.equal(guessKind({ name: "Costco Anywhere Visa Card by Citi" }), "credit");
assert.equal(guessKind({ name: "Cash Management (Individual)" }), "checking");
assert.equal(guessKind({ name: "Personal Loan" }), null);
assert.equal(guessKind({ name: "Mystery", klass: "Liability" }), "credit");
assert.equal(cleanMerchant("  COSTCO   WHSE ", "x"), "COSTCO WHSE");
assert.equal(cleanMerchant("", "Full text"), "Full text");
assert.equal(cleanMerchant("", ""), "(no description)");
console.log("tiller-sync-test: all checks passed");
