import assert from "node:assert/strict";
import { suspicion, authFailed } from "./phish-lib.mjs";
const s = (address, name, subject = "hello", extra = {}) => suspicion({ address, domain: address.split("@")[1], name, subject, ...extra });
assert.equal(s("alerts@notify.wellsfargo.com", "Wells Fargo").length, 0);
assert.equal(s("noreply@email.apple.com", "Apple").length, 0);
assert.equal(s("applearcade@insideapple.apple.com", "Apple Arcade").length, 0);
assert.equal(s("welcome@welcome.americanexpress.com", "American Express").length, 0);
assert.equal(s("x@purchase.com", "Purchase Desk").length, 0, "purchase is not chase");
assert.equal(s("x@pineapple-farms.com", "Pineapple Farms").length, 0);
assert.equal(s("store+1@g.shopifyemail.com", "Some Store").length, 0);
assert.equal(s("mail@mail2.wellsfargorewards.com", "Wells Fargo Rewards").length, 0);
for (const [a, n] of [["no_reply@post.applecard.apple", "Apple Card"], ["cloudwatch@aws.com", "Amazon Web Services"], ["x@e.fitbit.com", "Google Fitbit"], ["x@notifications.comcastbusiness.com", "Comcast Business"]]) assert.equal(s(a, n).length, 0, a);
assert.ok(s("a@wh.commufa.jp", "DocuSign").length > 0);
assert.ok(s("a@privatetoursmallorca.com", "Coinbase").length > 0);
assert.equal(s("a@e.smithsfdsmail.com", "Smiths", "Urgent: weekend deals", { replyDomain: "e.krogermail.com" }).length, 0);
assert.ok(s("support@wellsfargo-secure.com", "Wells Fargo").length > 0);
assert.ok(s("service@paypa1.com", "Service").length > 0);
assert.ok(s("x@evilapple.com", "Apple Support").length > 0, "suffix trick");
assert.ok(s("billing@random-host.ru", "Apple Billing").length > 0);
assert.ok(s("a@store.com", "Store", "Your order", { authFail: true }).length > 0);
assert.ok(s("a@store.com", "Store", "URGENT verify your account", { replyDomain: "gmail-help.top" }).length > 0);
assert.equal(s("a@store.com", "Store", "Your order", { replyDomain: "store-mail.com" }).length, 0);
assert.ok(authFailed("Authentication-Results: mx.me.com; dkim=pass\r\n spf=fail smtp.mailfrom=x\r\nSubject: x"));
assert.ok(!authFailed("Authentication-Results: mx.me.com; dkim=pass\r\n spf=pass\r\nSubject: x"));
console.log("phish: all checks passed");
